const test = require('node:test')
const assert = require('node:assert/strict')
const { readFileSync } = require('node:fs')
const { join } = require('node:path')
const read = file => readFileSync(join(__dirname, '..', file), 'utf8')

test('Core shipping UI shows the real Founding Member waiver source', () => {
  const catalog = read('src/catalog-view.ts')
  const service = read('src/services/catalog.ts')
  assert.match(service, /listShippingRateConfiguration/)
  assert.match(service, /foundingMemberFreeShippingSource/)
  assert.match(catalog, /shippingConfig\.foundingMemberFreeShippingSource/)
  assert.match(catalog, /Founding Member free shipping applies here/)
  assert.match(catalog, /founderSourceRow/)
})

test('Shipping rename preview describes the waiver transfer without modifying the rate or orders', () => {
  const catalog = read('src/catalog-view.ts')
  const sql = read('supabase/migrations/20261108035000_core_merge_shipping_sources.sql')
  assert.match(catalog, /Founding Member free shipping will automatically follow/)
  assert.match(catalog, /Historical orders stay unchanged/)
  assert.match(catalog, /result\.foundingWaiverMoved/)
  assert.match(catalog, /renameConfirm\?\.value !== renameFrom/)
  assert.match(sql, /v_old_rate IS DISTINCT FROM v_target_rate/)
  assert.match(sql, /IF v_waiver_moved THEN/)
  assert.match(sql, /foundingMemberFreeShippingSource/)
  assert.match(sql, /p_confirm_old_source IS DISTINCT FROM p_old_source/)
  assert.doesNotMatch(sql, /UPDATE public\.orders|UPDATE public\.invoices/i)
})
