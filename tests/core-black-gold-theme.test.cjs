const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const read = filename => fs.readFileSync(path.join(__dirname,'..',filename),'utf8')

test('Core global black-gold tokens replace brown and legacy blue styling without changing layout contracts',()=>{
  const css = read('src/champagne.css')
  const slate=read('src/slate.css')
  const styles=read('src/styles.css')
  const inventory=read('src/inventory.css')
  assert.match(css,/--core-black:#08090B/)
  assert.match(css,/--core-surface:#121416/)
  assert.match(css,/--core-raised:#1C1F22/)
  assert.match(css,/--core-gold:#D6AF61/)
  assert.match(css,/--core-champagne:var\(--core-gold\)/)
  assert.match(slate,/--sl-bg:#08090B/)
  assert.match(slate,/--sl-surface:#121416/)
  assert.match(slate,/--sl-accent:#D6AF61/)
  assert.match(slate,/--sl-control:#7D838A/)
  assert.doesNotMatch(slate,/#1D1A16|#29251F|#D4B47A/i)
  assert.doesNotMatch(css,/#1D1A16|#29251F|#D4B47A|#393126|#171511/i)
  assert.doesNotMatch(styles,/#0057FF|#00D2FF|#233044|#003FB8/i)
  assert.doesNotMatch(inventory,/#8B5CF6|#35393B/i)
})

