test('Core logo is a clean lowercase c without decorative dot in icon and all wordmarks',()=>{
  const icon=read('public/brand/core-app-icon.svg')
  const wordmark=read('public/brand/core.svg')
  const mark=read('public/brand-mark.svg')
  const main=read('src/main.ts')
  assert.match(icon,/aria-label="Core lowercase c app icon"/)
  assert.match(icon,/<path d="M665/)
  assert.match(icon,/stroke="#D6AF61"/)
  assert.doesNotMatch(icon,/<circle\b|core\.\s*app icon|#171A1C/i)
  assert.match(wordmark,/Core — Science By Hugs/)
  assert.match(wordmark,/>c<\/text>/)
  assert.match(mark,/lowercase c mark/)
  assert.doesNotMatch(mark,/<circle\b|>C<\/text>/)
  assert.equal((main.match(/class="core-wordmark-c"/g)||[]).length,3)
  assert.doesNotMatch(main,/>core<span>\.<\/span>/)
  assert.match(main,/const coreIconUrl =/)
})

test('PWA, browser and iPhone icons use black gold and retain the existing icon generation pipeline',()=>{
  const index=read('index.html')
  const vite=read('vite.config.ts')
  const ci=read('.github/workflows/ci.yml')
  const tokens=JSON.parse(read('public/brand/brand-tokens.json'))
  assert.match(index,/name="theme-color" content="#08090B"/)
  assert.match(index,/core-apple-touch-icon\.png/)
  assert.match(vite,/theme_color: '#08090B'/)
  assert.match(vite,/background_color: '#08090B'/)
  assert.match(vite,/short_name: 'core'/)
  for(const size of ['192','512']) {
    assert.match(ci,new RegExp('rsvg-convert -w '+size+' -h '+size+' public/brand/core-app-icon.svg'))
  }
  assert.match(ci,/rsvg-convert -w 180 -h 180 public\/brand\/core-app-icon.svg/)
  assert.equal(tokens.name,'Core — Black & Gold')
  assert.equal(tokens.colors.gold,'#D6AF61')
  assert.equal(tokens.colors.jetBlack,'#08090B')
})
