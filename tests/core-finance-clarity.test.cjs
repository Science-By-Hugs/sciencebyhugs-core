const test = require('node:test')
const assert = require('node:assert/strict')
const { readFileSync } = require('node:fs')
const { join } = require('node:path')
const read = f => readFileSync(join(__dirname, '..', f), 'utf8')

test('Core Finance separates paid, unverified and open order values', () => {
  const view = read('src/finance-view.ts')
  assert.match(view, /Paid order revenue/)
  assert.match(view, /Submitted · unverified/)
  assert.match(view, /Open order value/)
  assert.match(view, /Open orders and invoice totals can overlap/)
  assert.match(view, /orders marked paid, not bank deposits/)
  assert.match(view, /Orders & payments/)
  assert.match(view, /data-finance-profit-link/)
  assert.match(view, /scrollIntoView/)
  assert.doesNotMatch(view, /href="#finance-profit"/)
})

test('Profit highlights partial data coverage and never guesses missing historic costs', () => {
  const view = read('src/finance-view.ts')
  assert.match(view, /const costedLines = Math\.max\(0, t\.lines - t\.uncosted_lines\)/)
  assert.match(view, /const coverage = t\.lines > 0/)
  assert.match(view, /costedLines > 0 \? money\(t\.gross_profit\) : '—'/)
  assert.match(view, /role="progressbar"/)
  assert.match(view, /aria-valuenow/)
  assert.match(view, /not total business profit/)
  assert.match(view, /Missing historical costs are never estimated automatically/)
  assert.match(view, /Paid orders missing a paid-at timestamp|A paid order without that timestamp/)
})

test('Finance mobile design is responsive and no accounting records or checkout code changed', () => {
  const css = read('src/champagne.css')
  const view = read('src/finance-view.ts')
  assert.match(css, /\.finance-quality-head/)
  assert.match(css, /\.finance-quality-meter/)
  assert.match(css, /\.finance-shortcuts/)
  assert.match(css, /@media\(max-width:600px\)/)
  assert.doesNotMatch(view, /\.from\(['"](?:orders|payments|invoices|order_item_costs)['"]\)\.update/)
})
