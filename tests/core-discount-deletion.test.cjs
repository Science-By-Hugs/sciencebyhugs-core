const test=require('node:test')
const assert=require('node:assert/strict')
const fs=require('node:fs')
const path=require('node:path')
const read=p=>fs.readFileSync(path.join(__dirname,'..',p),'utf8')
const ui=read('src/discount-codes-panel.ts')
const backend=read('supabase/functions/core-discount-codes/index.ts')
const service=read('src/services/admin-tools.ts')
const sql=read('supabase/migrations/20261108014000_core_safe_unused_discount_delete.sql')
test('Delete is available only for unused, OFF, nonpermanent promotional codes',()=>{
  assert.match(ui,/export function canDeleteDiscountCode\(code: DiscountCodeRecord\)/)
  assert.match(ui,/!code\.permanent && !code\.active && !code\.used_at/)
  assert.match(ui,/!code\.used_order_id && !code\.used_by_profile_id/)
  assert.match(ui,/code\.kind === 'custom' \|\| code\.kind === 'free_shipping' \|\| code\.kind === 'referral_bonus'/)
  assert.match(ui,/canDeleteDiscountCode\(code\)/)
  assert.match(ui,/class="ghost compact dc-delete-open"/)
})
test('Deletion is typed-confirmed through the Core dialog, not an instant destructive button',()=>{
  assert.match(ui,/<dialog id="dc-delete-dialog"/)
  assert.match(ui,/id="dc-delete-input"/)
  assert.match(ui,/id="dc-delete-submit" disabled/)
  assert.match(ui,/deleteInput\.value !== selectedDelete\.code/)
  assert.match(ui,/deleteDialog\.showModal\(\)/)
  assert.match(ui,/await deleteUnusedDiscountCode\(code\.id, deleteInput\.value\)/)
  assert.match(ui,/deleteDialog\.close\(\)/)
  assert.match(ui,/Audit event recorded/)
  assert.doesNotMatch(ui,/from\(['"]discount_codes['"]\)\.delete/)
})
test('Backend enforces authenticated owner-admin and SQL atomic guard',()=>{
  assert.match(backend,/const role = lower\(user\.app_metadata\?\.role\)/)
  assert.match(backend,/if \(action === "delete"\)/)
  assert.match(backend,/admin\.rpc\("core_delete_unused_discount_code"/)
  assert.match(backend,/p_actor_user_id: user\.id/)
  assert.match(service,/export async function deleteUnusedDiscountCode\(id: string, confirmCode: string\)/)
  assert.match(service,/action: 'delete'/)
  assert.match(sql,/security invoker/)
  assert.match(sql,/where u\.id = p_actor_user_id/)
  assert.match(sql,/u\.raw_app_meta_data->>'role'/)
  assert.match(sql,/where id = p_id for update/)
  assert.match(sql,/p_confirm_code is distinct from d\.code/)
  assert.match(sql,/if d\.active then/)
  assert.match(sql,/if d\.permanent or d\.kind not in/)
  assert.match(sql,/d\.used_at is not null or d\.used_by_profile_id is not null or d\.used_order_id is not null/)
  assert.match(sql,/from public\.orders o/)
  assert.match(sql,/from public\.invoices i/)
  assert.match(sql,/insert into public\.core_audit_events/)
  assert.match(sql,/delete from public\.discount_codes/)
  assert.match(sql,/revoke all on function public\.core_delete_unused_discount_code/)
  assert.match(sql,/to service_role/)
})
test('No live production code is deleted or transformed during CI',()=>{
  const db=read('tests/core-discount-delete-db.sql')
  const ci=read('.github/workflows/ci.yml')
  assert.match(db,/BEGIN;/)
  assert.match(db,/ROLLBACK;/)
  assert.match(db,/SET LOCAL ROLE service_role/)
  assert.match(db,/Audit failure raises and must atomically undo/)
  assert.match(ci,/tests\/core-discount-delete-db\.sql/)
  assert.doesNotMatch(ci,/psql.+core.*prod|supabase db push/)
})
