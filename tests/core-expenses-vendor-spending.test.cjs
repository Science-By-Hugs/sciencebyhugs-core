const test=require('node:test')
const assert=require('node:assert/strict')
const {readFileSync}=require('node:fs')
const {join}=require('node:path')
const read=p=>readFileSync(join(__dirname,'..',p),'utf8')

test('Expenses workspace is included in Finances but does not change order or payment flows',()=>{
  const finance=read('src/finance-view.ts')
  const ui=read('src/finance-expenses-view.ts')
  assert.match(finance,/expensesPageMarkup\(\)/)
  assert.match(finance,/bindExpensesPage\(helpers\)/)
  assert.match(finance,/data-finance-expenses-link/)
  assert.match(ui,/Expenses & vendor spending/)
  assert.match(ui,/Purchase orders can also have manual paid expense entries/)
  assert.match(ui,/Received does not mean paid/)
  assert.match(ui,/not confirmed cash payments/)
})

test('Expenses use an RLS-protected manual-only ledger and strictly audited owner/admin mutation RPC',()=>{
  const sql=read('supabase/migrations/20261108040000_core_finance_expenses.sql')
  assert.match(sql,/CREATE TABLE IF NOT EXISTS public\.core_finance_expenses/)
  assert.match(sql,/ENABLE ROW LEVEL SECURITY/)
  assert.match(sql,/REVOKE ALL ON TABLE public\.core_finance_expenses FROM PUBLIC, anon, authenticated/)
  assert.match(sql,/GRANT SELECT, INSERT, UPDATE ON public\.core_finance_expenses TO service_role/)
  assert.doesNotMatch(sql,/GRANT DELETE ON public\.core_finance_expenses/i)
  const least=read('supabase/migrations/20261108041000_core_finance_expenses_least_privilege.sql')
  const rpcOnly=read('supabase/migrations/20261108041500_core_finance_expenses_rpc_only_writes.sql')
  assert.match(least,/REVOKE ALL ON TABLE public\.core_finance_expenses FROM service_role/)
  assert.match(rpcOnly,/REVOKE INSERT, UPDATE ON TABLE public\.core_finance_expenses FROM service_role/)
  assert.match(sql,/SECURITY DEFINER SET search_path = ''/)

  assert.match(sql,/FROM auth\.users u WHERE u\.id=p_actor_id/)
  assert.match(sql,/v_actor_role NOT IN \('owner','admin'\)/)
  assert.match(sql,/p_expected_updated_at/)
  assert.match(sql,/p_confirmation IS DISTINCT FROM 'VOID'/)
  assert.match(sql,/core_audit_events/)
  assert.match(sql,/IF v_old\.status='voided'/)
  assert.match(sql,/REVOKE ALL ON FUNCTION public\.core_manage_finance_expense/)
  assert.doesNotMatch(sql,/UPDATE public\.orders|UPDATE public\.payments|UPDATE public\.order_item_costs|UPDATE public\.inventory_purchase_orders/i)
})

test('Expense API verifies Core JWT and reads purchase orders as commitments not bank payments',()=>{
  const edge=read('supabase/functions/core-expenses/index.ts')
  assert.match(edge,/auth\.getUser\(\)/)
  assert.match(edge,/user\.app_metadata\?\.role/)
  assert.match(edge,/\["owner","admin"\]/)
  assert.match(edge,/p_actor_id:user\.id/)
  assert.match(edge,/core_manage_finance_expense/)
  assert.match(edge,/inventory_purchase_orders/)
  assert.match(edge,/inventory_purchase_lines/)
  assert.match(edge,/Number\(line\.packs_ordered\|\|0\)\*Number\(line\.pack_price_snapshot\|\|0\)/)
  assert.match(edge,/Math\.round\(\(merchandiseByPo/)
  assert.match(edge,/Purchase orders show recorded commitments, not verified payments/)
  assert.doesNotMatch(edge,/admin\.from\("orders"\)\.update\(/)
})

