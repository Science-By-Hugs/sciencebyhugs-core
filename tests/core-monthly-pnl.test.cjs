test('Never double count inventory POs, inbound vendor freight or planned expenses',()=>{
 const sql=read('supabase/migrations/20261108050000_core_monthly_profit_loss.sql')
 assert.match(sql,/category IN \('inventory_purchase','vendor_shipping'\)/)
 assert.match(sql,/purchase_orders,0/)
 assert.match(sql,/po_commitments/)
 assert.match(sql,/WHERE e\.status IN \('paid','planned'\)/)
 assert.match(sql,/paid_expense_records/)
 assert.match(sql,/recorded_operating_result/)
 assert.doesNotMatch(sql,/recorded_operating_result\s*=\s*.*po_commitments/)
 assert.doesNotMatch(sql,/UPDATE public\.(orders|payments|order_item_costs|core_finance_expenses)/)
})

test('Sale-time COGS takes precedence and missing evidence withholds operating result',()=>{
 const sql=read('supabase/migrations/20261108050000_core_monthly_profit_loss.sql')
 assert.match(sql,/c\.line_cost IS NOT NULL THEN c\.line_cost ELSE ce\.line_cost/)
 assert.match(sql,/missing_cost_lines>0/)
 assert.match(sql,/mismatched_order_totals>0/)
 assert.match(sql,/THEN NULL::numeric/)
 assert.match(sql,/core_finance_paid_date_evidence/)
 assert.doesNotMatch(sql,/product_costs|pc\.vendor_cost|orders\.created_at/)
})

test('Monthly finance API is read-only and only available with owner/admin authorization',()=>{
 const fn=read('supabase/functions/core-monthly-pnl/index.ts')
 const schema=read('supabase/migrations/20261108050000_core_monthly_profit_loss.sql')
 assert.match(fn,/auth\.getUser\(\)/)
 assert.match(fn,/app_metadata\?\.role/)
 assert.match(fn,/\["owner","admin"\]/)
 assert.match(fn,/core_monthly_profit_loss/)
 assert.match(fn,/result\.error\?\.code==="PGRST303"/)
 assert.doesNotMatch(fn,/\.update\(|\.insert\(|\.delete\(/)
 assert.match(schema,/SECURITY DEFINER SET search_path=''/)
 assert.match(schema,/REVOKE ALL ON FUNCTION public\.core_monthly_profit_loss\(integer\) FROM PUBLIC,anon,authenticated/)
 assert.match(schema,/GRANT EXECUTE ON FUNCTION public\.core_monthly_profit_loss\(integer\) TO service_role/)
})

test('Outbound shipping is explicitly recorded, not confused with inbound inventory freight',()=>{
 const categories=read('src/finance-expenses-view.ts')
 const model=read('src/services/expenses.ts')
 const migration=read('supabase/migrations/20261108045000_core_fulfillment_shipping_expenses.sql')
 assert.match(categories,/\['vendor_shipping','Inbound vendor shipping'\]/)
 assert.match(categories,/\['fulfillment_shipping','Outbound delivery & shipping'\]/)
 assert.match(model,/\|'fulfillment_shipping'\|/)
 assert.match(migration,/core_finance_expenses_category_check/)
 assert.match(migration,/v_category NOT IN \('inventory_purchase','vendor_shipping','fulfillment_shipping'/)
 assert.match(migration,/core_audit_events/)
})
