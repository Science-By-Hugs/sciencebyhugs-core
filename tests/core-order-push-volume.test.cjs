const test=require('node:test')
const assert=require('node:assert/strict')
const fs=require('node:fs')
const path=require('node:path')
const read=p=>fs.readFileSync(path.join(__dirname,'..',p),'utf8')
const sql=read('supabase/migrations/20261107192500_core_order_push_quiet_notifications.sql')

test('Core owner push fires for an order creation and manual payment review only',()=>{
  assert.match(sql,/when operation = 'INSERT' then 'new_order'/)
  assert.match(sql,/when operation = 'UPDATE'[\s\S]*?new_payment,''\)\)\) = 'submitted'/)
  assert.match(sql,/new_payment is distinct from old_payment/)
  assert.match(sql,/then 'payment_review'/)
  assert.match(sql,/else null/)
  assert.doesNotMatch(sql,/elsif NEW\.payment_status is distinct from OLD\.payment_status then\s*core_body/)
  assert.match(sql,/private\.core_order_push_kind\(\s*TG_OP,/)
  assert.match(sql,/if core_kind = 'new_order'/)
  assert.match(sql,/elsif core_kind = 'payment_review'/)
})
test('Core push volume is bounded by per-order deterministic event ids and a 10-minute cooldown',()=>{
  assert.match(sql,/'core-' \|\| core_kind \|\| ':' \|\| NEW\.id::text/)
  assert.match(sql,/on conflict \(event_key,user_id,app\) do nothing/)
  assert.match(sql,/q\.payload->>'tag' = 'order-' \|\| NEW\.id/)
  assert.match(sql,/q\.created_at > now\(\) - interval '10 minutes'/)
  assert.match(sql,/q\.user_id = s\.user_id and q\.app = 'core'/)
  assert.match(sql,/group by s\.user_id/)
  assert.match(sql,/lower\(u\.raw_app_meta_data->>'role'\) in \('owner','admin'\)/)
})
test('Nexus customer alerts and authorized subscription routing are preserved',()=>{
  assert.match(sql,/nexus_body := private\.order_push_customer_body\(/)
  assert.match(sql,/public\.native_push_devices/)
  assert.match(sql,/public\.profiles where id = NEW\.customer_id/)
  assert.match(sql,/q\.app = 'nexus'/)
  assert.match(sql,/values \(event_key, customer_auth, 'nexus'/)
  assert.match(sql,/set search_path = ''/)
  assert.match(sql,/revoke all on function private\.queue_order_push\(\)/)
  assert.doesNotMatch(sql,/drop trigger|delete from public\.app_push_subscriptions|alter table public\.orders/i)
})
