const test=require('node:test')
const assert=require('node:assert/strict')
const fs=require('node:fs')
const path=require('node:path')
const read=p=>fs.readFileSync(path.join(__dirname,'..',p),'utf8')
const src=read('src/notifications-view.ts')
const css=read('src/champagne.css')

test('Core operational alerts appear before customer broadcast tools',()=>{
  assert.ok(src.indexOf('id="notifications-root"')<src.indexOf('id="nexus-push-mode"'))
  assert.match(src,/id="comms-customer-messaging"/)
  assert.match(src,/id="comms-my-notifications"/)
  assert.match(src,/id="comms-adoption"/)
  assert.match(src,/class="comms-alert-priority"/)
  assert.match(src,/const urgent = s\.critical > 0/)
  assert.match(src,/s\.warning > 0/)
  assert.match(src,/No urgent operational alerts/)
  assert.match(src,/await loadCoreNotifications\(\)/)
  assert.match(src,/data\.notifications\.map\(item =>/)
})
test('Core alerts use accessible local severity filters without mutations',()=>{
  assert.match(src,/data-alert-filter="critical"/)
  assert.match(src,/data-alert-filter="warning"/)
  assert.match(src,/data-alert-filter="info"/)
  assert.match(src,/data-alert-severity="/)
  assert.match(src,/filters\.forEach\(button => button\.addEventListener\('click'/)
  assert.match(src,/other\.setAttribute\('aria-pressed'/)
  assert.match(src,/row\.hidden = category !== 'all'/)
  assert.match(css,/#notifications-root \.notification-row\[hidden\]/)
  assert.match(src,/helpers\.escapeHtml\(item\.detail\)/)
})
test('Customer push composer defaults to one eligible recipient, with a safe live preview',()=>{
  assert.match(src,/<option value="individual" selected>One customer<\/option>/)
  assert.match(src,/id="nexus-push-preview-title"/)
  assert.match(src,/id="nexus-push-preview-message"/)
  assert.match(src,/id="nexus-push-preview-audience"/)
  assert.match(src,/previewTitle\.textContent =/)
  assert.match(src,/previewMessage\.textContent =/)
  assert.match(src,/previewAudience\.textContent =/)
  assert.match(src,/subscribedCount === 0/)
  assert.match(src,/loadingRecipients/)
  assert.match(src,/sendButton\.disabled = sending/)
  assert.match(src,/sendMode\(\) === 'individual' && !customerSelect\?\.value/)
})
test('No Nexus notifications are sent by page render, preview or filtering',()=>{
  assert.match(src,/await loadNexusPushRecipients\(\)/)
  assert.match(src,/if \(!window\.confirm\('Send this Nexus notification to '/)
  assert.match(src,/await sendNexusPush\(\{ mode: targetMode, customerId, title, message \}\)/)
  assert.match(src,/Sending|Queuing…|Delivery will begin shortly/)
  assert.match(src,/void bindPushPanel\(\)/)
  assert.match(src,/void bindNexusOnboardingPanel\(helpers\)/)
  assert.match(src,/pushPanel\(\)/)
  assert.match(src,/nexusOnboardingPanelMarkup\(\)/)
  assert.doesNotMatch(src,/supabase\.functions\.invoke|setInterval\(|setTimeout\(/)
})
test('Messages remain mobile friendly, black-and-gold, and do not affect push registration',()=>{
  assert.match(css,/#notifications-root\{min-width:0;display:grid;gap:12px\}/)
  assert.match(css,/\.comms-alert-priority\{/)
  assert.match(css,/border-left:3px solid var\(--core-gold\)/)
  assert.match(css,/\.comms-disclosure>summary:focus-visible/)
  assert.match(css,/\.comms-preview\{/)
  assert.match(css,/@media\(max-width:760px\)\{/)
  assert.doesNotMatch(src,/unsubscribe|disablePush\(|delete from/i)
})
