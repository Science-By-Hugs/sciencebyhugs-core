const test=require('node:test')
const assert=require('node:assert/strict')
const fs=require('node:fs')
const path=require('node:path')
const read=p=>fs.readFileSync(path.join(__dirname,'..',p),'utf8')

test('Core has its own champagne identity distinct from Nexus slate and Pulse blue',()=>{
  const style=read('src/slate.css')
  const champagne=read('src/champagne.css')
  const main=read('src/main.ts')
  assert.match(style,/--sl-bg:#1D1A16/)
  assert.match(style,/--sl-accent:#D4B47A/)
  assert.match(champagne,/--core-champagne:#D4B47A/)
  assert.match(main,/import '\.\/champagne\.css'/)
})
test('five destinations retain older deep links and consolidate product/report navigation',()=>{
  const main=read('src/main.ts')
  assert.match(main,/\['products', 'Products', 'catalog'\]/)
  assert.match(main,/\['reports', 'Reports'\]/)
  assert.match(main,/\['referrals', 'Marketing'\]/)
  assert.match(main,/#products\?section=purchasing/)
  assert.match(main,/view === 'inventory' && \/\^#inventory/)
  assert.match(main,/productsTabs\(section\)/)
  assert.match(main,/reportsTabs\('finance'\)/)
})
test('Inventory separates stock, purchasing and suppliers while keeping actions bound',()=>{
  const inv=read('src/inventory-view.ts')
  const dash=read('src/inventory-dashboard.ts')
  assert.match(inv,/data-inventory-group="inventory"/)
  assert.match(inv,/data-inventory-group="purchasing"/)
  assert.match(inv,/data-inventory-group="suppliers"/)
  assert.match(inv,/mountMultiInventory\(root,data/)
  assert.match(inv,/mountInventoryAudit\(auditSlot,data/)
  assert.match(inv,/form\('inv-save-offer'/)
  assert.match(dash,/disclosure\.open=true/)
  assert.doesNotMatch(inv,/Live Nexus stock limits remain disabled/)
})
test('Today features owner actions without duplicating all-time analytics',()=>{
  const today=read('src/dashboard-view.ts')
  assert.match(today,/Review orders/)
  assert.match(today,/Check stock/)
  assert.match(today,/Receive inventory/)
  assert.match(today,/root\.innerHTML = stats \+ attention \+ quick \+ latest/)
  assert.doesNotMatch(today,/Revenue, all time/)
})
