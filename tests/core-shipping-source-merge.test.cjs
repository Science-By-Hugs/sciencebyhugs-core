test('Shipping source reassignments require typed confirmation and a verified Core owner/admin',()=>{
 assert.match(sql,/FROM auth\.users u WHERE u\.id=p_actor_id/)
 assert.match(sql,/u\.raw_app_meta_data->>'role'/)
 assert.match(sql,/v_actor_role NOT IN \('owner','admin'\)/)
 assert.match(sql,/p_confirm_old_source IS DISTINCT FROM p_old_source/)
 assert.match(sql,/SECURITY DEFINER SET search_path = ''/)
 assert.match(sql,/REVOKE ALL ON FUNCTION public\.core_catalog_merge_shipping_source/)
 assert.match(sql,/TO service_role/)
 assert.match(edge,/if \(action === "merge_shipping_source"\)/)
 assert.match(edge,/const role = String\(user\.app_metadata\?\.role/)
 assert.match(edge,/p_actor_id: user\.id/)
 assert.match(api,/export async function mergeShippingSource/)
})
test('Source merge preserves existing matching rate and moves product assignments, waiver and audit atomically',()=>{
 assert.match(sql,/FROM public\.internal_runtime_config WHERE key='checkout' FOR UPDATE/)
 assert.match(sql,/IF NOT v_rates \? p_new_source THEN/)
 assert.match(sql,/v_old_rate IS DISTINCT FROM p_expected_rate/)
 assert.match(sql,/v_old_rate IS DISTINCT FROM v_target_rate/)
 assert.match(sql,/WHERE p\.shipping_from=p_old_source/)
 assert.match(sql,/SET shipping_from=p_new_source,updated_at=now\(\)/)
 assert.match(sql,/v_rates-p_old_source/)
 assert.match(sql,/foundingMemberFreeShippingSource/)
 assert.match(sql,/INSERT INTO public\.core_audit_events/)
 assert.match(sql,/GET DIAGNOSTICS v_product_count=ROW_COUNT/)
 assert.doesNotMatch(sql,/UPDATE public\.orders|UPDATE public\.invoices|DELETE FROM public\.products/i)
})
